import { chromium } from 'playwright';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:5179/', { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => window.__valley?.world);
  await page.evaluate(() => __valley.start());
  await page.locator('#craft-button').click();
  await page.waitForSelector('.workshop-links');
  const text = await page.locator('.workshop-links').innerText();
  assert.match(text, /现在背包里有/);
  assert.match(text, /点想做的东西/);
  assert.match(text, /盖房子/);
  assert.doesNotMatch(text, /减法/);
  assert.doesNotMatch(text, /−/);
  assert.doesNotMatch(text, /放满就出现/);
  assert.match(text, /弯弯小球道/);
  assert.match(text, /我的小角落/);
  assert.match(text, /能放大东西的箱子/);
  assert.match(text, /我的小屋/);
  assert.doesNotMatch(text, /继续做/);
  const house = page.locator('.workshop-fold[data-fold="house"]');
  assert.equal(await house.getAttribute('open'), '');
  await house.locator('summary').click();
  assert.equal(await house.evaluate(el => el.open), false);
  await house.locator('summary').click();
  assert.equal(await house.evaluate(el => el.open), true);
  await page.locator('.workshop-fold[data-fold="mat"] summary').click();
  assert.equal(await house.evaluate(el => el.open), false);
  assert.equal(await page.locator('.workshop-fold[data-fold="mat"]').evaluate(el => el.open), true);
  await house.locator('summary').click();
  assert.equal(await house.evaluate(el => el.open), true);
  assert.equal(await page.locator('.workshop-fold[data-fold="mat"]').evaluate(el => el.open), false);
  await page.locator('.workshop-fold[data-fold="toy"] summary').click();
  await page.locator('[data-action="workshop-want"][data-recipe="ball"]').click();
  await page.waitForSelector('[data-recipe-row="ball"]');
  assert.ok(await page.locator('[data-recipe-row="ball"] .add-plus').count() >= 1);
  assert.equal(await page.locator('[data-recipe-row="ball"] .eq-out .add-plus').count(), 0);
  assert.match(await page.locator('[data-recipe-row="ball"] .eq-result-box').innerText(), /木球/);
  assert.match(await page.locator('[data-recipe-row="ball"] .eq-result-box').innerText(), /×1/);
  await page.locator('[data-recipe-row="ball"] [data-action="math-pit"]').first().click();
  await page.waitForFunction(() => document.querySelector('[data-recipe-row="ball"] [data-math="sum"]').textContent === '1');
  await page.locator('[data-recipe-row="ball"] [data-action="math-pit"]').last().click();
  await page.waitForFunction(() => document.querySelector('[data-recipe-row="ball"] [data-math="sum"]').textContent.includes('1 + 1 = 2'));
  assert.match(await page.locator('[data-recipe-row="ball"] [data-math="gain"]').innerText(), /得到 1 个木球/);
  await page.locator('.combo-details summary').click();
  const plank = await page.locator('.combo-tree .combo-card', { hasText: '木板' }).boundingBox();
  const stick = await page.locator('.combo-tree .combo-card', { hasText: '木棍' }).boundingBox();
  const post = await page.locator('.combo-tree .combo-card', { hasText: '挡板' }).boundingBox();
  assert.ok(plank.y > (await page.locator('.combo-tree .combo-card', { hasText: '木料' }).boundingBox()).y);
  assert.ok(stick.y > plank.y);
  assert.ok(post.y > stick.y);
  await page.locator('.workshop-fold[data-fold="mat"] summary').click();
  await page.locator('[data-action="workshop-want"][data-recipe="planks"]').click();
  const woodBefore = await page.evaluate(() => __valley.game.state.inventory.wood);
  const plankBefore = await page.evaluate(() => __valley.game.state.inventory.plank);
  await page.locator('[data-recipe-row="planks"] [data-action="workshop-goal"]').click();
  await page.waitForFunction(([wood, plank]) => __valley.game.state.inventory.wood === wood - 1 && __valley.game.state.inventory.plank === plank + 4, [woodBefore, plankBefore]);
  const status = await page.locator('#workshop-status').innerText();
  assert.match(status, /已经放进背包/);
  assert.match(status, /4 块木板/);
  assert.equal(await page.locator('[data-pack-item="plank"] b').innerText(), String(plankBefore + 4));
  assert.match(await page.locator('[data-recipe-row="planks"]').getAttribute('class'), /is-shown/);
  assert.equal(await page.locator('[data-recipe-row="chest"]').count(), 0);
  await page.locator('.build-case', { hasText: '能放大东西的箱子' }).locator('[data-action="workshop-goal"][data-recipe="chest"]').isDisabled().then(disabled => assert.equal(disabled, true));
  const rampBefore = await page.evaluate(() => ({ plank: __valley.game.state.inventory.plank, stone: __valley.game.state.inventory.stone, ramp: __valley.game.state.inventory.ramp }));
  await page.locator('.build-case', { hasText: '弯弯小球道' }).locator('[data-action="workshop-goal"]').nth(1).click();
  await page.waitForFunction(before => __valley.game.state.inventory.ramp === before.ramp + 1, rampBefore);
  const ramp = await page.locator('#workshop-status').innerText();
  assert.match(ramp, /已经放进背包/);
  assert.match(ramp, /斜坡/);
  assert.equal(await page.evaluate(() => __valley.game.state.inventory.plank), rampBefore.plank - 1);
  assert.equal(await page.evaluate(() => __valley.game.state.inventory.stone), rampBefore.stone - 1);
  await page.locator('.workshop-fold[data-fold="house"] summary').click();
  await page.locator('[data-action="workshop-want"][data-recipe="door"]').click();
  await page.waitForSelector('[data-recipe-row="door"]');
  assert.match(await page.locator('[data-recipe-row="door"] .eq-result-box').innerText(), /门/);
  const packPlank = await page.locator('[data-pack-item="plank"] b').innerText();
  const invPlank = await page.evaluate(() => String(__valley.game.state.inventory.plank));
  assert.equal(packPlank, invPlank);
  assert.match(await page.locator('[data-recipe-row="door"] [data-have-item="plank"]').innerText(), new RegExp(`背包 ${invPlank}`));
  assert.match(await page.locator('[data-math="lack"]').innerText(), /木棍还差/);
  assert.match(await page.locator('[data-math="lack"]').innerText(), /木作工作台/);
  assert.equal(await page.locator('[data-pack-item="stick"] b').innerText(), '0');
  await page.evaluate(() => __valley.game.mutate(s => { s.inventory.plank = 0; }));
  await page.locator('[data-action="workshop-want"][data-recipe="roof"]').click();
  await page.waitForSelector('[data-recipe-row="roof"]');
  assert.equal(await page.locator('[data-pack-item="plank"] b').innerText(), '0');
  assert.match(await page.locator('[data-math="lack"]').innerText(), /木板还差/);
  assert.match(await page.locator('[data-math="lack"]').innerText(), /木作工作台/);
  console.log(status);
  console.log(ramp);
  assert.deepEqual(errors, []);
} finally {
  await browser.close();
}
